import AppKit
import LinkPresentation
import QuickLookThumbnailing

/// Polls the pasteboard, skips private/transient copies, and hands new ones to the store.
final class ClipboardWatcher {
    static let shared = ClipboardWatcher()

    static let concealedTypes: Set<String> = ["org.nspasteboard.ConcealedType"]
    static let transientTypes: Set<String> = ["org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
                                              "de.petermaurer.TransientPasteboardType"]
    static let passwordManagers: Set<String> = ["com.1password.1password", "com.agilebits.onepassword7", "com.agilebits.onepassword-osx",
                                                "com.agilebits.onepassword4", "com.apple.Passwords", "com.apple.keychainaccess",
                                                "com.bitwarden.desktop"]
    static let maxBytes = 100 << 20

    private var lastChange = NSPasteboard.general.changeCount
    private var timer: Timer?
    private let queue = DispatchQueue(label: "com.heetpatel.cubby.capture", qos: .utility)
    var store = Store.shared

    func start() {
        let t = Timer(timeInterval: 0.25, repeats: true) { [weak self] _ in self?.tick() }
        t.tolerance = 0.05
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    /// Call right after we write the pasteboard ourselves, so our own write isn't captured.
    func ignoreCurrent() { lastChange = NSPasteboard.general.changeCount }

    private func tick() {
        let pb = NSPasteboard.general
        let change = pb.changeCount
        guard change != lastChange else { return }
        if Settings.isPaused { lastChange = change; return }
        // A writer clears first and fills after (same changeCount), so an empty board means "look again next tick".
        guard let items = pb.pasteboardItems, !items.isEmpty, items.contains(where: { !$0.types.isEmpty }) else { return }
        lastChange = change
        let app = NSWorkspace.shared.frontmostApplication
        let types = Set(items.flatMap { $0.types.map(\.rawValue) })
        if let why = Self.skipReason(types: types, bundleID: app?.bundleIdentifier, confidential: Settings.ignoreConfidential,
                                     transient: Settings.ignoreTransient, ignored: Settings.ignoredApps) { return log("skipped copy: \(why)") }
        if Settings.soundEffects { NSSound(named: "Pop")?.play() }

        // ponytail: read on main (NSPasteboard isn't documented thread-safe); move off-main if huge images stutter.
        var total = 0
        var snapshot: [PayloadItem] = items.map { it in
            var data: [String: Data] = [:]
            var order: [String] = []
            for t in it.types { if let d = it.data(forType: t) { data[t.rawValue] = d; order.append(t.rawValue); total += d.count } }
            return PayloadItem(types: order, data: data)
        }
        guard total <= Self.maxBytes else { return log("skipped copy: \(total) bytes is over the limit") }
        // Link Cleaner: swap the clipboard for the clean link right away, so a plain ⌘V anywhere pastes it clean.
        var cleaned: (original: String, removed: Int)?
        if Settings.cleanLinks, let c = LinkCleaner.clean(snapshot) {
            snapshot = c.items
            cleaned = (c.original, c.removed)
            pb.clearContents()
            pb.writeObjects(snapshot.map(\.pasteboardItem))
            ignoreCurrent()
        }
        let date = Date()
        queue.async { [store] in
            Self.ingest(snapshot, bundleID: app?.bundleIdentifier, appName: app?.localizedName, date: date, store: store, cleanedFrom: cleaned)
        }
    }

    static func skipReason(types: Set<String>, bundleID: String?, confidential: Bool = true, transient: Bool = true,
                           ignored: [String] = []) -> String? {
        if confidential && !types.isDisjoint(with: concealedTypes) { return "concealed" }
        if transient && !types.isDisjoint(with: transientTypes) { return "transient" }
        if confidential, let b = bundleID, passwordManagers.contains(b) { return "password manager \(b)" }
        if let b = bundleID, ignored.contains(b) { return "ignored app \(b)" }
        return nil
    }

    /// Classify → dedupe → insert → fetch late previews. Runs on the capture queue.
    @discardableResult
    static func ingest(_ items: [PayloadItem], bundleID: String?, appName: String?, date: Date, store: Store, latePreviews: Bool = true,
                       cleanedFrom: (original: String, removed: Int)? = nil,
                       detectSecrets: Bool = Settings.detectSecrets, secretLifetime: TimeInterval? = Settings.secretLifetime) -> Int64? {
        guard items.contains(where: { !$0.data.isEmpty }) else { return nil }
        let r = Classifier.analyze(items)
        if let id = store.bump(checksum: r.checksum, at: date, secretLifetime: secretLifetime) { return id }
        let secret = detectSecrets && r.kind == .text ? r.string.flatMap(SecretDetector.check) : nil
        var (preview, search) = Classifier.preview(r, items)
        if let c = cleanedFrom, r.kind == .link { preview.originalURL = c.original; preview.trackersRemoved = c.removed }
        let id = store.insert(.init(kind: r.kind, checksum: r.checksum, preview: preview, searchText: search, payload: items,
                                    appBundleID: bundleID, appName: appName, sensitive: secret != nil,
                                    expiresAt: secret == nil ? nil : secretLifetime.map { date.addingTimeInterval($0) }), at: date)
        guard let id, latePreviews else { return id }
        log("captured \(r.kind.label.lowercased()) from \(appName ?? "?")")
        if r.kind == .link, Settings.linkPreviews, let s = preview.url, let url = URL(string: s) { DispatchQueue.main.async { fetchLink(id, url, store) } }
        if r.kind == .file, let path = preview.paths?.first { fileThumbnail(id, path, store) }
        return id
    }

    /// Page title + og-image, filled in after the card is already showing.
    private static func fetchLink(_ id: Int64, _ url: URL, _ store: Store) {
        let provider = LPMetadataProvider()
        provider.timeout = 10
        provider.startFetchingMetadata(for: url) { meta, _ in
            guard let meta else { return }
            let title = meta.title
            guard let ip = meta.imageProvider ?? meta.iconProvider else {
                return store.updatePreview(id) { if $0.title == nil { $0.title = title } }
            }
            ip.loadObject(ofClass: NSImage.self) { obj, _ in
                let thumb = (obj as? NSImage).flatMap { Classifier.thumbnail($0) }
                store.updatePreview(id) { p in
                    if p.title == nil { p.title = title }
                    if thumb != nil { p.thumb = thumb }
                }
            }
        }
    }

    /// Quick Look thumbnail (a real picture for images/PDFs, the icon otherwise).
    private static func fileThumbnail(_ id: Int64, _ path: String, _ store: Store) {
        let req = QLThumbnailGenerator.Request(fileAt: URL(fileURLWithPath: path), size: CGSize(width: 96, height: 96), scale: 2,
                                               representationTypes: .thumbnail)
        QLThumbnailGenerator.shared.generateBestRepresentation(for: req) { rep, _ in
            guard let cg = rep?.cgImage, let data = Classifier.encode(cg) else { return }
            store.updatePreview(id) { $0.thumb = data }
        }
    }
}
